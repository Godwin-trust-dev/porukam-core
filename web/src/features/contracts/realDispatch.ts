/**
 * Единая развилка real/мок для страниц договорного контура (ADR-088).
 *
 * Вне mock-режима ЛЮБОЙ id — реальный контур: у боевого бэка id — UUID,
 * неймспейса `rc-*` у них нет (`rc-*` — только realContractsDb в MSW), и
 * уход по префиксу в старый мок-агрегат ронял карточку/подписание/этап
 * (§E-смоук 2026-08-18). В mock-режиме прежнее правило: `rc-*` — реальный
 * контур, иначе — старый агрегат, всё ещё живой для страниц вне фаз
 * редизайна (тот же приём, что `contractHandlers.ts` на мок-слое).
 */
export function isRealContractId(id: string): boolean {
  return (import.meta.env.VITE_API_MODE ?? 'mock') !== 'mock' || id.startsWith('rc-');
}
