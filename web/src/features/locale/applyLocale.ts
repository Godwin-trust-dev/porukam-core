import type { i18n as I18nInstance } from 'i18next';
import { loadLocaleResources } from '@porukam/i18n';
import { recoverFromStaleChunk } from '../../app/chunkRecovery';

/**
 * Переключение активного языка: СНАЧАЛА подгрузить пакет, потом
 * `changeLanguage` (docs/tasks/Задача_feat_l10n-launch-surfaces.md §A).
 *
 * Порядок принципиален. 27 из 29 языков лежат ленивыми чанками (ADR-089), и
 * `changeLanguage` до их прихода перерисовывает весь экран по EN-фолбэку — то
 * самое «язык выбран, а текст английский», которое запрещает §0. Разница в
 * пару сотен миллисекунд на чанк, но без неё правило нарушается на каждом
 * переключении.
 *
 * Если чанк не пришёл (нет сети/язык не в сборке) — язык всё равно
 * переключаем: `<html lang>`/`dir` и `Accept-Language` должны соответствовать
 * выбору человека, а недостающие ключи закроет EN-фолбэк (§3 постановки —
 * защита, не норма).
 */
export async function applyLocale(instance: I18nInstance, code: string): Promise<void> {
  try {
    await loadLocaleResources(instance, code);
  } catch {
    // Отличаем «языка нет в этой сборке» от «чанк не доехал»:
    // `loadLocaleResources` для первого возвращает `false` БЕЗ исключения, а
    // сюда мы попадаем только когда `import()` упал — то есть файла нет по
    // тому имени, которое помнит оболочка. После деплоя это ожидаемо: хеш в
    // имени чанка сменился (01.09, регрессия выбора языка).
    //
    // Раньше здесь стоял пустой catch, и дальше язык переключался всё равно:
    // пакета нет → каждый ключ уходит в EN-фолбэк → «выбран русский, а текст
    // английский», молча. Перезагрузка забирает свежую оболочку с верными
    // именами; попытка одна на вкладку (см. `chunkRecovery`).
    if (recoverFromStaleChunk()) return;
    console.warn(`[i18n] языковой пакет «${code}» не загрузился — интерфейс пойдёт по EN-фолбэку`);
  }
  if (instance.language !== code) await instance.changeLanguage(code);
}
