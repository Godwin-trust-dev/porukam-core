import { api } from '../../shared/api';

/**
 * Шаги конструктора договора — ЕДИНСТВЕННЫЙ поведенческий слой продукта
 * (док метрик §8.1, ADR-145). Он заведён потому, что брошенный черновик иначе
 * неизмерим: доменного события «бросил на шаге 3» не существует и не должно
 * существовать — договор о шагах формы ничего не утверждает.
 *
 * Что уходит на сервер: код шага, действие, идентификатор черновика. И всё.
 * Ни пользователя, ни IP, ни значений полей формы — иначе узкий слой
 * превращается в клиентский трекинг, от которого документ отказывается
 * сознательно (§9.4), и аналитический контур перестаёт быть совместимым
 * с уничтожением ключа субъекта.
 *
 * Отправка НИКОГДА не мешает работе мастера: ошибки проглатываются молча,
 * ответ не ожидается. Метрика, ради которой пользователь увидел ошибку
 * сохранения договора, не стоит ничего.
 */
export type ConstructorStepAction = 'entered' | 'completed' | 'left';

export function trackConstructorStep(
  stepCode: string,
  action: ConstructorStepAction,
  contractId?: string | null,
): void {
  if (!stepCode) return;
  void api
    .request<void>('/analytics/constructor-step', {
      method: 'POST',
      body: { step_code: stepCode, action, ...(contractId ? { contract_id: contractId } : {}) },
    })
    .catch(() => {
      /* аналитика не имеет права ломать мастер — молчим */
    });
}
