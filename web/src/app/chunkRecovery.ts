/**
 * Восстановление после «протухшей оболочки» (01.09, регрессия выбора языка).
 *
 * Проблема. Имена чанков содержат хеш содержимого, и деплой их меняет. У
 * клиента, который держит вкладку открытой (или получил старый index из
 * кэша/service worker), в памяти остаются СТАРЫЕ имена. Запрос такого чанка
 * после выката возвращает честную 404 (`конфиг nginx`,
 * `try_files $uri =404`), и любой `import()` падает.
 *
 * Для языков это било молча и потому хуже всего: 27 из 29 пакетов —
 * ленивые чанки (ADR-089), а `applyLocale` при неудаче всё равно переключал
 * язык. Пакета нет → каждый ключ уходит в EN-фолбэк → «выбран русский, а
 * интерфейс английский», без ошибки и без объяснения.
 *
 * Лечение — перезагрузка: она забирает свежий index с новыми именами чанков.
 * Ровно на это рассчитывал комментарий в nginx-конфиге («честная 404, которую
 * SPA умеет обработать перезагрузкой») — обработки при этом не существовало.
 *
 * Ограничение ОДНОЙ перезагрузкой на вкладку обязательно: если чанка нет не
 * из-за протухшей оболочки, а потому что его правда нет (сломанная сборка,
 * offline), безусловная перезагрузка дала бы бесконечный цикл. Флаг живёт в
 * `sessionStorage` — то есть в этой вкладке; новая вкладка получит одну свою
 * попытку, и это верно: там оболочка уже свежая.
 */
const RELOAD_KEY = 'pr:stale-chunk-reload';

/**
 * Пытается восстановиться перезагрузкой. `true` — перезагрузка запущена
 * (вызывающему делать больше нечего), `false` — попытка уже была или
 * хранилище недоступно, работаем как есть.
 */
export function recoverFromStaleChunk(): boolean {
  try {
    if (sessionStorage.getItem(RELOAD_KEY)) return false;
    sessionStorage.setItem(RELOAD_KEY, new Date().toISOString());
  } catch {
    // Приватный режим/выключенные куки — считать попытки негде, а
    // перезагружаться без счётчика опаснее, чем остаться на EN-фолбэке.
    return false;
  }
  window.location.reload();
  return true;
}

/**
 * Тот же случай для чанков МАРШРУТОВ: Vite шлёт `vite:preloadError`, когда
 * не смог подтянуть модуль страницы. Без обработчика человек упирался в
 * экран ошибки с кнопкой «Повторить» — то есть чинил деплой руками.
 */
export function installChunkRecovery(): void {
  window.addEventListener('vite:preloadError', (event) => {
    if (recoverFromStaleChunk()) event.preventDefault();
  });
}
