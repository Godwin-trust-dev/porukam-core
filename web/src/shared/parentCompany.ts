/**
 * Автор продукта — Trust Dev (https://trust-dev.com/), владелец
 * «По рукам». Один источник правды: имя, адрес и правило выбора языковой
 * версии. Лежит в `shared/`, а не в `features/publicSite/`, потому что
 * подпись стоит в двух местах: подвал витрины и экран «О проекте» внутри
 * приложения. Решение владельца 30.10.2026: *«мы сделали сайт о нашей
 * деятельности… надо бы ссылку в порукам добавить done by or made by.
 * Текст только на английском и русском пока. пусть читают кому интересно»*.
 *
 * Почему имя — константа в коде, а не ключ i18n: это имя собственное, и
 * в логотипе самой компании оно латиницей на всех языках. На русской
 * версии их сайта в тексте стоит «Технологии доверия», но подмешивать
 * сюда второе написание значило бы завести второй факт о том же — а
 * заголовок ссылки всё равно ведёт на страницу, где имя написано так,
 * как компания его пишет сама.
 *
 * Почему не из env (как `VITE_SOCIAL_*` в SocialLinks): соцсети на
 * момент того решения ещё не существовали, и флаг там нужен, чтобы не
 * показывать пустые иконки. Здесь скрывать нечего, а ссылка обязана
 * попасть в ПРЕРЕНДЕРЕННЫЙ html (ADR-196) — значит её адрес должен быть
 * известен сборке без прод-окружения.
 */
export const PARENT_COMPANY_NAME = 'Trust Dev';

const PARENT_COMPANY_URL_EN = 'https://trust-dev.com/';
const PARENT_COMPANY_URL_RU = 'https://trust-dev.com/ru/';

/**
 * Адрес сайта компании под язык страницы. У сайта пока два языка (английский
 * и русский) — поэтому 28 локалей, кроме `ru`, ведут на английскую версию,
 * ровно как кадры интерфейса на лендинге (`siteShotLang`): лучше честный
 * английский, чем ссылка на страницу, которой нет.
 */
export function parentCompanyUrl(locale: string): string {
  return locale === 'ru' ? PARENT_COMPANY_URL_RU : PARENT_COMPANY_URL_EN;
}
